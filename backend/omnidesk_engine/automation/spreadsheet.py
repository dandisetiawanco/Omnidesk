from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from omnidesk_engine.db import Database
from omnidesk_engine.security.journal import sha256_file
from omnidesk_engine.security.policy import validate_child_path, validate_scoped_directory


def _style_header(ws: Any, headers: list[str]) -> None:
    ws.append(headers)
    header_fill = PatternFill(start_color="11161F", end_color="11161F", fill_type="solid")
    header_font = Font(name="Calibri", size=11, bold=True, color="F0F4F8")
    for col_idx in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=col_idx)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="left", vertical="center")
    ws.freeze_panes = "A2"


def _autofit_columns(ws: Any) -> None:
    for col in ws.columns:
        max_len = 10
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            val = "" if cell.value is None else str(cell.value)
            max_len = max(max_len, min(len(val) + 3, 64))
        ws.column_dimensions[col_letter].width = max_len


def generate_organization_workbook(
    db: Database,
    task_id: str,
    step_id: str,
    directory: str | Path,
    inspection: dict[str, Any],
    moved_files: list[dict[str, Any]],
    report_filename: str | None = None,
    allowed_roots: list[str] | None = None,
) -> dict[str, Any]:
    root = validate_scoped_directory(directory, allowed_roots=allowed_roots)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    fname = report_filename or f"OmniDesk_Organization_Report_{stamp}.xlsx"
    if not fname.endswith(".xlsx"):
        fname += ".xlsx"
    report_path = validate_child_path(root, root / fname)

    wb = Workbook()

    # Sheet 1: Summary
    ws_summary = wb.active
    ws_summary.title = "Summary"
    _style_header(ws_summary, ["Metric", "Value"])
    summary_rows = [
        ("Generated By", "OmniDesk Universal AI Computer Operator"),
        ("Generated At (UTC)", datetime.now(timezone.utc).isoformat()),
        ("Target Directory", str(root)),
        ("Total Files Inspected", inspection.get("total_files", 0)),
        ("Files Organized (Moved)", len(moved_files)),
        ("Files Deleted", 0),
        ("Potential Duplicate Groups (SHA-256)", inspection.get("duplicate_group_count", 0)),
        ("Total Duplicate Files Flagged", inspection.get("duplicate_file_count", 0)),
        ("Total Size (KB)", round(inspection.get("total_bytes", 0) / 1024, 2)),
    ]
    for metric, value in summary_rows:
        ws_summary.append([metric, value])

    ws_summary.append(["", ""])
    ws_summary.append(["Category Breakdown", "File Count"])
    for cat, count in sorted(inspection.get("categories", {}).items()):
        ws_summary.append([cat, count])
    _autofit_columns(ws_summary)

    # Sheet 2: Organized Files
    ws_files = wb.create_sheet("Organized Files")
    _style_header(
        ws_files,
        ["File Name", "Category", "Size (Bytes)", "Original Path", "New Path", "SHA-256 (Verified)"],
    )
    if moved_files:
        for item in moved_files:
            ws_files.append(
                [
                    item.get("file_name", ""),
                    item.get("category", ""),
                    item.get("size_bytes", 0),
                    item.get("source_path", ""),
                    item.get("dest_path", ""),
                    item.get("sha256", ""),
                ]
            )
    else:
        for item in inspection.get("files", []):
            ws_files.append(
                [
                    item.get("name", ""),
                    item.get("category", ""),
                    item.get("size_bytes", 0),
                    item.get("path", ""),
                    "(Dry-run / unchanged)",
                    item.get("sha256") or "",
                ]
            )
    _autofit_columns(ws_files)

    # Sheet 3: Potential Duplicates
    ws_dups = wb.create_sheet("Potential Duplicates")
    _style_header(
        ws_dups,
        ["SHA-256 Digest", "Size (Bytes)", "Duplicate Count", "Files", "Action Taken"],
    )
    duplicates = inspection.get("duplicates", [])
    if duplicates:
        for group in duplicates:
            ws_dups.append(
                [
                    group.get("sha256", ""),
                    group.get("size_bytes", 0),
                    group.get("count", 0),
                    ", ".join(group.get("files", [])),
                    "Preserved (no files deleted)",
                ]
            )
    else:
        ws_dups.append(["None detected", 0, 0, "All files had unique content hashes", "No action needed"])
    _autofit_columns(ws_dups)

    wb.save(report_path)
    digest = sha256_file(report_path)
    db.record_journal(task_id, step_id, "create_file", str(report_path), str(report_path), sha256=digest)

    return {
        "report_path": str(report_path),
        "file_name": report_path.name,
        "size_bytes": report_path.stat().st_size,
        "sha256": digest,
        "sheets": ["Summary", "Organized Files", "Potential Duplicates"],
    }
