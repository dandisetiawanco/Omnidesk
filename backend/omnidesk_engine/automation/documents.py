from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from omnidesk_engine.db import Database
from omnidesk_engine.security.journal import sha256_file
from omnidesk_engine.security.policy import validate_child_path, validate_scoped_directory


def generate_markdown_report(
    db: Database,
    task_id: str,
    step_id: str,
    directory: str | Path,
    title: str,
    sections: list[tuple[str, str]],
    filename: str | None = None,
    allowed_roots: list[str] | None = None,
) -> dict[str, Any]:
    root = validate_scoped_directory(directory, allowed_roots=allowed_roots)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    fname = filename or f"OmniDesk_Summary_{stamp}.md"
    if not fname.endswith(".md"):
        fname += ".md"
    target = validate_child_path(root, root / fname)

    lines = [
        f"# {title}",
        "",
        f"Generated by OmniDesk at {datetime.now(timezone.utc).isoformat()}",
        "",
    ]
    for heading, body in sections:
        lines.append(f"## {heading}")
        lines.append("")
        lines.append(body)
        lines.append("")

    target.write_text("\n".join(lines), encoding="utf-8")
    digest = sha256_file(target)
    db.record_journal(task_id, step_id, "create_file", str(target), str(target), sha256=digest)
    return {
        "report_path": str(target),
        "file_name": target.name,
        "size_bytes": target.stat().st_size,
        "sha256": digest,
    }
